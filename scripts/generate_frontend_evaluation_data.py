from __future__ import annotations

import json
from pathlib import Path
from typing import Any, TypedDict


PROJECT_ROOT = Path(__file__).resolve().parents[1]

EVAL_RESULTS_PATH = PROJECT_ROOT / "data/eval-results.json"
TEST_QUESTIONS_PATH = PROJECT_ROOT / "data/test-questions.json"
FAILURE_ANALYSIS_PATH = PROJECT_ROOT / "data/failure-analysis.json"

OUTPUT_PATH = PROJECT_ROOT / "src/generated/evaluation-data.ts"


class SourceFile(TypedDict):
    name: str
    path: Path


SOURCE_FILES: list[SourceFile] = [
    {
        "name": "evaluation result sets",
        "path": EVAL_RESULTS_PATH,
    },
    {
        "name": "failure analysis entries",
        "path": FAILURE_ANALYSIS_PATH,
    },
    {
        "name": "test questions",
        "path": TEST_QUESTIONS_PATH,
    },
]


def load_json(path: Path) -> Any:
    with path.open(encoding="utf-8") as file:
        return json.load(file)


def to_typescript_literal(data: Any) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False)


def build_generated_file(
    eval_results: Any,
    test_questions: Any,
    failure_analysis_list: Any,
) -> str:
    return f"""/**
 * Generated evaluation data for the frontend dashboard.
 *
 * Do not edit this file manually.
 * Regenerate it with:
 * uv run python scripts/generate_frontend_evaluation_data.py
 *
 * Source files:
 * - data/eval-results.json
 * - data/test-questions.json
 * - data/failure-analysis.json
 */

import type {{ EvaluationResults }} from "../types/evaluation";
import type {{ FailureAnalysis, TestQuestion }} from "../lib/types";

export const evalResults = {to_typescript_literal(eval_results)} satisfies EvaluationResults;

export const testQuestions = {to_typescript_literal(test_questions)} satisfies TestQuestion[];

export const failureAnalysisList = {to_typescript_literal(failure_analysis_list)} satisfies FailureAnalysis[];
"""


def main() -> None:
    for source_file in SOURCE_FILES:
        loaded_data = load_json(source_file["path"])
        print(f"loaded {len(loaded_data)} {source_file['name']}")

    eval_results = load_json(EVAL_RESULTS_PATH)
    test_questions = load_json(TEST_QUESTIONS_PATH)
    failure_analysis_list = load_json(FAILURE_ANALYSIS_PATH)

    generated_file = build_generated_file(
        eval_results=eval_results,
        test_questions=test_questions,
        failure_analysis_list=failure_analysis_list,
    )

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(generated_file, encoding="utf-8")

    print(f"generated {OUTPUT_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()